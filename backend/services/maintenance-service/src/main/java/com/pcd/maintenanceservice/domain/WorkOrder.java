package com.pcd.maintenanceservice.domain;

import com.pcd.shared.error.BusinessRuleViolationException;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.EnumSet;
import java.util.Objects;
import java.util.Set;
import java.util.UUID;
import java.util.stream.Stream;

@Entity
@Table(name = "work_orders")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class WorkOrder {

    public static final Set<WorkOrderStatus> OPEN = EnumSet.of(WorkOrderStatus.SCHEDULED, WorkOrderStatus.IN_PROGRESS);
    private static final int MAX_TITLE_LENGTH = 120;

    @Id
    private UUID id;

    @Version
    private long version;

    private UUID vehicleId;

    @Enumerated(EnumType.STRING)
    private WorkOrderKind kind;

    @Enumerated(EnumType.STRING)
    private WorkOrderPriority priority;

    @Enumerated(EnumType.STRING)
    private WorkOrderStatus status;

    private String title;

    private String description;

    private String vendor;

    private LocalDate scheduledFor;

    private boolean autoGenerated;

    private Instant startedAt;

    private Instant completedAt;

    private Long odometerKm;

    private BigDecimal partsCost;

    private BigDecimal laborCost;

    private String resolutionNotes;

    private String cancellationReason;

    private Instant overdueNotifiedAt;

    @CreationTimestamp
    private Instant createdAt;

    @UpdateTimestamp
    private Instant updatedAt;

    public record Plan(UUID vehicleId, WorkOrderKind kind, WorkOrderPriority priority, String title,
                       String description, String vendor, LocalDate scheduledFor) {

        public Plan {
            Objects.requireNonNull(vehicleId, "vehicleId is required");
            Objects.requireNonNull(kind, "kind is required");
            Objects.requireNonNull(priority, "priority is required");
            Objects.requireNonNull(scheduledFor, "scheduledFor is required");
            if (title == null || title.isBlank() || title.strip().length() > MAX_TITLE_LENGTH) {
                throw new IllegalArgumentException("title must be between 1 and %d characters".formatted(MAX_TITLE_LENGTH));
            }
            title = title.strip();
            description = blankToNull(description);
            vendor = blankToNull(vendor);
        }
    }

    public static WorkOrder schedule(Plan plan, boolean autoGenerated) {
        WorkOrder order = new WorkOrder();
        order.id = UUID.randomUUID();
        order.status = WorkOrderStatus.SCHEDULED;
        order.autoGenerated = autoGenerated;
        order.apply(plan);
        return order;
    }

    public Plan plan() {
        return new Plan(vehicleId, kind, priority, title, description, vendor, scheduledFor);
    }

    public void replan(Plan plan) {
        requireStatus(EnumSet.of(WorkOrderStatus.SCHEDULED), "changed");
        if (!plan.vehicleId().equals(vehicleId)) {
            throw new BusinessRuleViolationException("A work order cannot move to another vehicle");
        }
        apply(plan);
        overdueNotifiedAt = null;
    }

    public void start(Instant now) {
        requireStatus(EnumSet.of(WorkOrderStatus.SCHEDULED), "started");
        status = WorkOrderStatus.IN_PROGRESS;
        startedAt = now;
    }

    public void complete(Instant now, BigDecimal parts, BigDecimal labor, Long odometer, String notes) {
        requireStatus(EnumSet.of(WorkOrderStatus.IN_PROGRESS), "completed");
        Stream.of(parts, labor).filter(Objects::nonNull).filter(amount -> amount.signum() < 0).findAny()
                .ifPresent(negative -> {
                    throw new IllegalArgumentException("Costs must not be negative");
                });
        if (odometer != null && odometer < 0) {
            throw new IllegalArgumentException("odometerKm must not be negative");
        }
        status = WorkOrderStatus.COMPLETED;
        completedAt = now;
        partsCost = parts;
        laborCost = labor;
        odometerKm = odometer;
        resolutionNotes = blankToNull(notes);
    }

    public void cancel(String reason) {
        requireStatus(OPEN, "cancelled");
        if (reason == null || reason.isBlank()) {
            throw new IllegalArgumentException("A cancellation reason is required");
        }
        status = WorkOrderStatus.CANCELLED;
        cancellationReason = reason.strip();
    }

    public boolean isOverdue(LocalDate today) {
        return status == WorkOrderStatus.SCHEDULED && scheduledFor.isBefore(today);
    }

    public boolean markOverdueNotified(Instant now) {
        if (overdueNotifiedAt != null) {
            return false;
        }
        overdueNotifiedAt = now;
        return true;
    }

    public BigDecimal totalCost() {
        return Stream.of(partsCost, laborCost).filter(Objects::nonNull).reduce(BigDecimal.ZERO, BigDecimal::add);
    }

    private void apply(Plan plan) {
        vehicleId = plan.vehicleId();
        kind = plan.kind();
        priority = plan.priority();
        title = plan.title();
        description = plan.description();
        vendor = plan.vendor();
        scheduledFor = plan.scheduledFor();
    }

    private void requireStatus(Set<WorkOrderStatus> allowed, String action) {
        if (!allowed.contains(status)) {
            throw new BusinessRuleViolationException("Work order %s is %s and cannot be %s".formatted(title, status, action));
        }
    }

    private static String blankToNull(String value) {
        return value == null || value.isBlank() ? null : value.strip();
    }
}
